      <div class="card-clean">
        <h2 class="fw-bold section-title mb-3">Plagiarism Policy</h2>

        <p>
          Authors should ensure the originality of their contents, while preparing a manuscript draft. In case the authors have used the work and/or words of others this must be appropriately cited or quoted
        </p>

        <p>
           All the articles submitted to IJACS shall be screened for plagiarism using iThenticate (online plagiarism detection software). In case, plagiarism is detected during review/editorial process, such manuscript(s) will be rejected immediately.
        </p>

        <p>
          If the plagiarism is proven after publication, such manuscript(s) will be retracted from the journal and appropriate announcement will be placed in this regards. We can also consider appropriate action against authors depending upon the seriousness of the case. It includes;
        </p>

        <ul>
          <li>Debarring the authors from publication in future.</li>
          <li>We can bring such instants in notice of author's funding agencies, author's institutes (where they works) and to the original authors whose work has been plagiarized.</li>
        </ul>

        <p>COPE flow charts (please follow below link) shall also be considered while dealing with plagiarism complaints.</p>

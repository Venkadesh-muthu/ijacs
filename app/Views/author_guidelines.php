  <!-- Types of Contributions -->
  <section class="py-5">
    <div class="container">
      <div class="content-card">
        <h2 class="fw-bold accent-1">Types of Contributions</h2>

        <p>
          Manuscripts submitted to the Journal of Advances Chemical Sciences should be <strong><em>Short Communication</em></strong>, <strong><em>Review</em></strong> or <strong><em>Full Paper</em></strong> or <strong><em>Concept</em></strong> or <strong><em>Books</em></strong> or <strong><em>Comments &amp; Responses</em></strong>.
        </p>
        <h4 class="mt-3 fw-semibold accent-1">IJACS has the following features:</h4>
        <h4 class="mt-3 fw-semibold accent-1">Short Communication</h4>
        <p>
          Short Communication is a report/note in unusual urgency. A statement from author justifying its need is required. Short Communication should be confined to 1500 words or 2 pages. The text should be divided into sections however, an introductory paragraph should provide a general context of the work explaining its significance and indicating why it should be of interest to scientists in other areas while the end paragraph should summarize the essential conclusions and implications.
        </p>

        <h4 class="mt-3 fw-semibold accent-1">Full Paper</h4>
        <p>
          Full Paper must either be of a contemporary interest or of great significance to a more specialized readership. It should be peer reviewed, reporting the details of studies that have not been published previously, except in the form of primary communications. Manuscript should be divided into sections including “Experimental”. Full paper should be restricted to 10000 words or 9–12 pages.
        </p>

        <h4 class="mt-3 fw-semibold accent-1">Review</h4>
        <p>
          Review introduces the reader to a particular area of an author’s research through a concise overview of a selected topic. The content should balance scope with depth. Reference to important work from others that is significant to the topic should be included. There is no restriction placed on the length of the Review.
        </p>

        <h4 class="mt-3 fw-semibold accent-1">Book Reviews</h4>
        <p>
          Covers reviews of current books on Chemical Science.
        </p>

        <p>
          All <strong><em>tables</em></strong>, <strong><em>charts</em></strong>, and <strong><em>graphs</em></strong> should be in colour. Wherever necessary, the source should be indicated at the bottom. Number and complexity of exhibits should be minimal. Endnotes, italics, and quotation marks should be kept to the minimum.
        </p>
      </div>
    </div>
  </section>

  <!-- Review Process -->
  <section class="py-5 bg-light">
    <div class="container">
      <div class="content-card">
        <h2 class="fw-bold accent-1">Review Process</h2>

        <p>
          <em><strong>IJACS</strong></em> operates a <strong>strictly blind peer review process</strong> in which the reviewer’s name is withheld from the author and the author’s name from the reviewer. The reviewer may at their own discretion opt to reveal their name to the author in their review but our standard policy practice is for both identities to remain concealed.
        </p>

        <p>
          Two or more referees review all contributions by following the ‘double blind’ system. The process usually takes about <strong>8 to 30 working days</strong>.
        </p>

        <p>
          IJACS reserves the right to implement the editorial amendments in the final draft of the manuscript to suit the journal’s requirements.
        </p>
      </div>
    </div>
  </section>

  <!-- Conflict of Interest / Withdrawal -->
  <section class="py-5">
    <div class="container">
      <div class="content-card">
        <h2 class="fw-bold accent-1">Conflict of Interest</h2>
        <p>
          All the authors must disclose the possible conflicts of interest/Competing Interests they may have with publication of the manuscript or an institution or product that is mentioned in the manuscript and/or is important to the outcome of the study presented. Authors should also disclose conflict of interest with products that compete with those mentioned in their manuscript. The Conflict of Interest statement should list each author separately by name.
        </p>

        <h3 class="mt-4 fw-bold accent-1">Article Withdrawal Policy</h3>
        <p>
          Only used for Articles in Press which represent early versions of articles and sometimes contain errors, or may have been accidentally submitted twice. Occasionally, but less frequently, the articles may represent infringements of professional ethical codes, such as multiple submission, bogus claims of authorship, plagiarism, fraudulent use of data or the like.
        </p>
        <p>
          Articles in Press (articles that have been accepted for publication but which have not been formally published and will not yet have the complete volume/issue/page information) that include errors, or are discovered to be accidental duplicates of other published article(s), or are determined to violate our journal publishing ethics guidelines in the view of the editors (such as multiple submission, bogus claims of authorship, plagiarism, fraudulent use of data or the like), may be “Withdrawn” from KROS Publications. Withdrawn means that the article content (HTML and PDF) is removed and replaced with a HTML page and PDF simply stating that the article has been withdrawn according to the KROS Publication Policy on Article in Press Withdrawal with a link to the current policy document.
        </p>
      </div>
    </div>
  </section>

  <!-- Plagiarism / Actions -->
  <section class="py-5 bg-light">
    <div class="container">
      <div class="content-card">
        <h2 class="fw-bold accent-1">Plagiarism Policy</h2>

        <p>
          By submitting paper for publication to the journal, you as contributor/author/co-author state that you are fully aware that plagiarism is wrong and you know that plagiarism is the use of another person’s idea or published work and pretend that it is one’s own.
        </p>
        <p>
          You declare that each contribution to your work from other people’s published or unpublished sources have been acknowledged and the source of information have been referenced. You certify that you will not allow anyone to copy your work with the intention of passing it off as his/her own work. You certify that you are solely responsible for any incomplete reference that may remain in your work.
        </p>

        <h3 class="mt-3 fw-bold accent-1">Action against Plagiarism</h3>
        <p>
          When plagiarism has been found to have occurred, the IJACS will take the actions listed below as determined by the type of plagiarism. Unless determined otherwise during the investigation, all authors are deemed to be individually and collectively responsible for the content of a plagiarizing paper.
        </p>
        <p>
          The IJACS may inform the department chair, dean, or supervisor of the authors of the finding of plagiarism. The authors will be asked to write a formal letter of apology to the authors of the plagiarized paper, including an admission of plagiarism. If the paper has appeared on the website, the journal will remove access to the full text. The paper itself will be kept in the database for future research or legal purposes.
        </p>
        <p>
          If the paper is under submission, the paper can be automatically rejected by the editor-in-chief without further revisions and without any further plagiarism investigation coordinated by the IJACS.
        </p>
      </div>
    </div>
  </section>


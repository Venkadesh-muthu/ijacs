        <h2 class="fw-bold accent-1">Acknowledgement</h2>
        <p>All acknowledgments (if any) should be included at the very end of the paper before the references and may include supporting grants, presentations, and so forth.</p>

        <h3 class="mt-4 fw-bold accent-1">Abbreviations</h3>
        <p>Standard abbreviations should be used throughout the manuscript. All nonstandard abbreviations should be kept to a minimum and must be defined in the text following their first use.</p>

        <h3 class="mt-4 fw-bold accent-1">Copyright</h3>
        <p>
          Wherever copyrighted material is used, the authors should be accurate in reproduction and obtain permission from copyright holders, if necessary.
        </p>
        <p>
          Articles published in IJACS should not be reproduced or reprinted in any form, either in full or in part, without prior written permission from the Editor.
        </p>

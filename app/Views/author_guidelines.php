  <section class="py-5">
    <div class="container">
      <div class="content-card">
        <h2 class="fw-bold accent-1">Preparation of Manuscript</h2>

        <p>
          The manuscript should be typed, double-spaced on standard-sized paper (A4) with 1" margins on all sides. Times New Roman font 12 pt should be used. The fonts used in the text as well as graphics should be restricted to Times New Roman, Symbol and Zapf Dingbats.
        </p>

        <h3 class="mt-4 fw-bold accent-1">Title page</h3>
        <p>
          The title page should contain a clear, concise and informative title of the article followed by the names and affiliations of the authors. The affiliation should comprise the department, institution, city, and state (or nation) and should be typed as a footnote to the author's name. The Corresponding Author must indicate his or her complete mailing address, office/cellular phone number, fax number, and email address at the lower left of the Title Page.
        </p>
      </div>
    </div>
  </section>

  <!-- Article Structure -->
  <section class="py-5 bg-light">
    <div class="container">
      <div class="content-card">
        <h2 class="fw-bold accent-1">Article Structure</h2>

        <h3 class="fw-semibold text-primary">Abstract</h3>
        <p>
          The abstract should not be more than 220 words and should contain objectives, material and methods, Results and Conclusions. Reviews and mini-reviews also require an abstract. Abstract should not be structured. Abstract must be followed by four–six keywords.
        </p>

        <h3 class="fw-semibold text-primary">Introduction</h3>
        <p>
          This should be brief and indicate aim of the study and the essential background information. Introduction should clearly state the hypothesis or purpose statement, how and why the purpose or hypothesis was developed and why the author deems it important.
        </p>

        <h3 class="fw-semibold text-primary">Material and methods</h3>
        <p>
          Please provide concise but complete information about the material and the analytical, statistical and experimental procedures used. This part should be as clear as possible to enable other scientists to repeat the research presented. The use of subheadings to divide the text is encouraged.
        </p>
        <p>
          Primary headings should be in BOLD CAPITAL LETTERS. Secondary or subheadings should be in bold sentence case. Third level subheadings should be in italicized sentence case. In case of animal/human experiments or clinical trials authors must give the details of ethical approval.
        </p>

        <h3 class="fw-semibold text-primary">Result and Discussion</h3>
        <p>
          Data acquired from the research with appropriate statistical analysis described in the methods section should be included in this section. In this part, the same data/information given in a table must not be repeated in a figure, or vice versa. Tables and Figures should be self explanatory and it is not acceptable to repeat extensively the numerals from tables into text and give lengthy and unnecessary explanations of the Tables and Figures.
        </p>
        <p>
          Discussion should relate the results to current understanding of the scientific problems being investigated in the field.
        </p>

        <h3 class="fw-semibold text-primary">Conclusion</h3>
        <p>
          This should clearly explain the main conclusions of the work highlighting its importance and relevance.
        </p>

        <h3 class="fw-semibold text-primary">Biographical sketch</h3>
        <p>
          The manuscript should accompany the following: a brief biographical sketch (50–75 words) of the author/s describing a passport-type photo and a short summary of the career to-date of corresponding author should be included (current designation and affiliation, specialization, number of books and articles published in refereed journals, and membership on editorial boards and companies, etc.).
        </p>

      </div>
    </div>
  </section>

